# gen_opcodes.py - writes lib/opcodes.asm: the W65C02S opcode table for the monitor
#   python tools/gen_opcodes.py
# For every opcode: mnemonic number and addressing mode (OP_MN, OP_MD, 256 bytes each), then the
# mnemonics (3 letters each). RMB/SMB/BBR/BBS get their bit number (opcode bits 4-6) when printed.
MODES = ['IMP', 'ACC', 'IMM', 'ZP', 'ZPX', 'ZPY', 'ABS', 'ABX', 'ABY', 'IND', 'INX', 'INY', 'ZPI', 'REL', 'AIX', 'ZPR']
OPS = {}
def op(code, mn, mode):
    OPS[code] = (mn, mode)
# the NMOS 6502 set
for base, mn in [(0x00, 'ORA'), (0x20, 'AND'), (0x40, 'EOR'), (0x60, 'ADC'), (0x80, 'STA'), (0xA0, 'LDA'), (0xC0, 'CMP'), (0xE0, 'SBC')]:
    for off, mode in [(0x01, 'INX'), (0x05, 'ZP'), (0x09, 'IMM'), (0x0D, 'ABS'), (0x11, 'INY'), (0x15, 'ZPX'), (0x19, 'ABY'), (0x1D, 'ABX'), (0x12, 'ZPI')]:
        if mn == 'STA' and mode == 'IMM':
            continue
        op(base + off, mn, mode)
for base, mn in [(0x00, 'ASL'), (0x20, 'ROL'), (0x40, 'LSR'), (0x60, 'ROR')]:
    op(base + 0x06, mn, 'ZP'); op(base + 0x0A, mn, 'ACC'); op(base + 0x0E, mn, 'ABS')
    op(base + 0x16, mn, 'ZPX'); op(base + 0x1E, mn, 'ABX')
for base, mn in [(0xC0, 'DEC'), (0xE0, 'INC')]:
    op(base + 0x06, mn, 'ZP'); op(base + 0x0E, mn, 'ABS'); op(base + 0x16, mn, 'ZPX'); op(base + 0x1E, mn, 'ABX')
for code, mn in [(0x10, 'BPL'), (0x30, 'BMI'), (0x50, 'BVC'), (0x70, 'BVS'), (0x90, 'BCC'), (0xB0, 'BCS'), (0xD0, 'BNE'), (0xF0, 'BEQ'), (0x80, 'BRA')]:
    op(code, mn, 'REL')
for code, mn in [(0x00, 'BRK'), (0x08, 'PHP'), (0x18, 'CLC'), (0x28, 'PLP'), (0x38, 'SEC'), (0x40, 'RTI'), (0x48, 'PHA'), (0x58, 'CLI'),
                 (0x60, 'RTS'), (0x68, 'PLA'), (0x78, 'SEI'), (0x88, 'DEY'), (0x8A, 'TXA'), (0x98, 'TYA'), (0x9A, 'TXS'), (0xA8, 'TAY'),
                 (0xAA, 'TAX'), (0xB8, 'CLV'), (0xBA, 'TSX'), (0xC8, 'INY'), (0xCA, 'DEX'), (0xD8, 'CLD'), (0xE8, 'INX'), (0xEA, 'NOP'),
                 (0xF8, 'SED'), (0x5A, 'PHY'), (0x7A, 'PLY'), (0xDA, 'PHX'), (0xFA, 'PLX'), (0xCB, 'WAI'), (0xDB, 'STP')]:
    op(code, mn, 'IMP')
op(0x1A, 'INC', 'ACC'); op(0x3A, 'DEC', 'ACC')
op(0x20, 'JSR', 'ABS'); op(0x4C, 'JMP', 'ABS'); op(0x6C, 'JMP', 'IND'); op(0x7C, 'JMP', 'AIX')
op(0x24, 'BIT', 'ZP'); op(0x2C, 'BIT', 'ABS'); op(0x89, 'BIT', 'IMM'); op(0x34, 'BIT', 'ZPX'); op(0x3C, 'BIT', 'ABX')
op(0x04, 'TSB', 'ZP'); op(0x0C, 'TSB', 'ABS'); op(0x14, 'TRB', 'ZP'); op(0x1C, 'TRB', 'ABS')
op(0x64, 'STZ', 'ZP'); op(0x74, 'STZ', 'ZPX'); op(0x9C, 'STZ', 'ABS'); op(0x9E, 'STZ', 'ABX')
op(0x84, 'STY', 'ZP'); op(0x8C, 'STY', 'ABS'); op(0x94, 'STY', 'ZPX')
op(0x86, 'STX', 'ZP'); op(0x8E, 'STX', 'ABS'); op(0x96, 'STX', 'ZPY')
op(0xA0, 'LDY', 'IMM'); op(0xA4, 'LDY', 'ZP'); op(0xAC, 'LDY', 'ABS'); op(0xB4, 'LDY', 'ZPX'); op(0xBC, 'LDY', 'ABX')
op(0xA2, 'LDX', 'IMM'); op(0xA6, 'LDX', 'ZP'); op(0xAE, 'LDX', 'ABS'); op(0xB6, 'LDX', 'ZPY'); op(0xBE, 'LDX', 'ABY')
op(0xC0, 'CPY', 'IMM'); op(0xC4, 'CPY', 'ZP'); op(0xCC, 'CPY', 'ABS')
op(0xE0, 'CPX', 'IMM'); op(0xE4, 'CPX', 'ZP'); op(0xEC, 'CPX', 'ABS')
for b in range(8):
    op(0x07 + b * 16, 'RMB', 'ZP'); op(0x87 + b * 16, 'SMB', 'ZP')
    op(0x0F + b * 16, 'BBR', 'ZPR'); op(0x8F + b * 16, 'BBS', 'ZPR')
assert len(OPS) == 212   # the opcodes defined by the W65C02S
names = ['???'] + sorted({m for m, _ in OPS.values()})
out = [';;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;',
       ';                                                              ;',
       ';   OPCODES.ASM  -  W65C02S opcode table (generated by         ;',
       ';   tools/gen_opcodes.py: do not edit by hand)                 ;',
       ';                                                              ;',
       ';;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;',
       '']
for i, m in enumerate(MODES):
    out.append(f'M_{m:<10}= {i}')
out.append(f'MN_RMB      = {names.index("RMB")}')
out.append(f'MN_SMB      = {names.index("SMB")}')
out.append(f'MN_BBR      = {names.index("BBR")}')
out.append(f'MN_BBS      = {names.index("BBS")}')
out.append(f'MN_COUNT    = {len(names)}')
out.append('')
out.append('OP_MN:                   ; mnemonic number of each opcode (0 = ???)')
for row in range(16):
    out.append('  .byte ' + ','.join(str(names.index(OPS[c][0])) if c in OPS else '0' for c in range(row * 16, row * 16 + 16)))
out.append('OP_MD:                   ; addressing mode of each opcode')
for row in range(16):
    out.append('  .byte ' + ','.join(str(MODES.index(OPS[c][1])) if c in OPS else '0' for c in range(row * 16, row * 16 + 16)))
out.append('MN_TXT:                  ; 3 letters each')
for i in range(0, len(names), 8):
    out.append('  .byte ' + ','.join(f'"{n}"' for n in names[i:i + 8]))
open('lib/opcodes.asm', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(f'{len(OPS)} opcodes, {len(names)} mnemonics')
